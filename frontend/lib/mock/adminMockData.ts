// ============================================
// HELPER FUNCTIONS
// ============================================

export function getTournamentById(
  id: string
): TournamentWithMetrics | undefined {
  return mockTournaments.find((t) => t.id === id);
}

export function getAgentById(id: string): Agent | undefined {
  return mockAgents.find((a) => a.id === id);
}

export function getAgentStatesByTournament(tournamentId: string): AgentState[] {
  return mockAgentStates.filter((as) => as.tournament_id === tournamentId);
}

export function getTradesByTournament(tournamentId: string): Trade[] {
  return mockTrades
    .filter((t) => t.tournament_id === tournamentId)
    .sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime());
}

export function getTradesByAgent(agentId: string): Trade[] {
  return mockTrades
    .filter((t) => t.agent_id === agentId)
    .sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime());
}
